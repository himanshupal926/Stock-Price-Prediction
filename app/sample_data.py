"""Generate a small SYNTHETIC dataset (daily prices + headlines) so the app runs offline.

Run directly to regenerate:  python -m app.sample_data

The data is made up. Headline mood has a weak, deliberately planted link to the next
day's return so the demo has something to find. That says nothing about real markets.
To use real data, replace data/prices.csv and data/news.csv (see README) and delete
data/SYNTHETIC_DATA.txt.
"""
import numpy as np
import pandas as pd

from .config import DATA_DIR, SEED

TICKERS = ["ACME", "NOVA", "ORBT", "ZENO"]
N_DAYS = 900

POSITIVE = [
    "{T} beats quarterly estimates as demand surges",
    "{T} raises full-year guidance after strong sales",
    "Analysts upgrade {T} on record growth",
    "{T} wins major contract, shares rally",
    "{T} reports profit jump and expands margins",
    "Investors cheer {T} product launch as orders soar",
]
NEGATIVE = [
    "{T} cuts outlook amid weak demand",
    "{T} misses earnings estimates as costs rise",
    "Analysts downgrade {T} as sales slow",
    "{T} faces investigation over accounting concerns",
    "{T} announces layoffs after steep loss",
    "{T} shares tumble on product recall",
]
NEUTRAL = [
    "{T} schedules investor day for next month",
    "{T} announces leadership change",
    "{T} to present at industry conference",
    "{T} files routine regulatory update",
    "{T} appoints new head of operations",
    "{T} confirms date for annual shareholder meeting",
]


def generate(data_dir=DATA_DIR, seed=SEED):
    data_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    dates = pd.bdate_range("2021-01-04", periods=N_DAYS)
    price_rows, news_rows = [], []

    for ticker in TICKERS:
        mood = rng.normal(size=N_DAYS)            # hidden "news mood" of each day
        noise = rng.normal(0, 0.012, N_DAYS)
        ret = np.zeros(N_DAYS)
        for t in range(N_DAYS - 1):               # mood today nudges tomorrow's return
            ret[t + 1] = 0.0003 + 0.004 * mood[t] + 0.05 * ret[t] + noise[t + 1]
        close = 100 * np.exp(np.cumsum(ret))
        prev = np.r_[100.0, close[:-1]]
        open_ = prev * np.exp(rng.normal(0, 0.002, N_DAYS))
        high = np.maximum(open_, close) * np.exp(np.abs(rng.normal(0, 0.004, N_DAYS)))
        low = np.minimum(open_, close) * np.exp(-np.abs(rng.normal(0, 0.004, N_DAYS)))
        volume = (1_000_000 * np.exp(rng.normal(0, 0.25, N_DAYS) + 15 * np.abs(ret))).astype(int)

        for i, d in enumerate(dates):
            price_rows.append((d.date().isoformat(), ticker, round(open_[i], 2), round(high[i], 2),
                               round(low[i], 2), round(close[i], 2), int(volume[i])))
            for _ in range(min(rng.poisson(1.3), 4)):
                tone = mood[i] + rng.normal(0, 0.8)   # headlines are a noisy view of the mood
                pool = POSITIVE if tone > 0.5 else NEGATIVE if tone < -0.5 else NEUTRAL
                news_rows.append((d.date().isoformat(), ticker, str(rng.choice(pool)).format(T=ticker)))

    pd.DataFrame(price_rows, columns=["date", "ticker", "open", "high", "low", "close", "volume"]) \
        .to_csv(data_dir / "prices.csv", index=False)
    pd.DataFrame(news_rows, columns=["date", "ticker", "headline"]).to_csv(data_dir / "news.csv", index=False)
    (data_dir / "SYNTHETIC_DATA.txt").write_text(
        "prices.csv and news.csv were generated by app/sample_data.py. They are synthetic.\n"
        "Delete this file after replacing them with real data.\n")


if __name__ == "__main__":
    generate()
    print(f"Sample data written to {DATA_DIR}")
